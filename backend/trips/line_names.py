DEFAULT_TRAIN_TYPE = "普通"  # 보통(각역 정차)은 따로 보여주지 않는다
_TRAIN_TYPE_PATTERN = re.compile("(" + "|".join(sorted(TRAIN_TYPES, key=len, reverse=True)) + ")$")

_OPERATOR_PATTERN = re.compile("^(" + "|".join(sorted((re.escape(k) for k in OPERATORS), key=len, reverse=True)) + ")")
_SHINKANSEN_PATTERN = re.compile("^(" + "|".join(sorted(SHINKANSEN, key=len, reverse=True)) + ")新幹線$")


def _normalize(text):
    """전각 문자(ＪＲ 등)를 반각으로 맞추고 공백을 정리한다."""
    return re.sub(r"\s+", " ", unicodedata.normalize("NFKC", text or "")).strip()


def korean_line_name(name):
    """
    노선·버스 이름의 한국어 표기. 사전에 없으면 원문(전각 문자만 반각으로 정리)을 돌려준다.
    예: ＪＲ山手線 → JR야마노테선, 東京メトロ半蔵門線 → 도쿄메트로 한조몬선, 都営大江戸線 → 도에이 오에도선
    """
    text = _normalize(name)
    if not text:
        return ""
    if "バス" in text or text.endswith("交通"):
        return _korean_bus(text)

    prefix_ko, rest = "", text
    match = _OPERATOR_PATTERN.match(text)
    if match:
        prefix_ko = OPERATORS[match.group(1)]
        rest = text[match.end():].strip()
    if not rest and prefix_ko:
        return prefix_ko.strip()  # 운영사 이름만 남은 경우(예: 東京モノレール)
    translated = _korean_line_part(rest)
    if translated is None:
        return text
    return prefix_ko + translated


def _korean_line_part(rest):
    if rest in LINES:
        return LINES[rest]
    shinkansen = _SHINKANSEN_PATTERN.match(rest)
    if shinkansen:
        return f"{SHINKANSEN[shinkansen.group(1)]} 신칸센"
    if rest == "新幹線":
        return "신칸센"
    if "・" in rest:  # 결합 노선: 京浜東北線・根岸線 -> 게이힌도호쿠선·네기시선 (모든 부분을 알 때만)
        parts = [LINES.get(part) for part in rest.split("・")]
        if all(parts):
            return "·".join(parts)
    return None


def _korean_bus(text):
    for japanese, korean in sorted(BUS_OPERATORS.items(), key=lambda item: -len(item[0])):
        if japanese in text:
            return text.replace(japanese, korean).strip()
    return text.replace("バス", "버스")


def korean_line_and_type(raw_name, transport_type=""):
    """
    노선 이름과 열차 종별을 나눠 한국어로 돌려준다.
    {"line_name": "JR교토선", "line_name_ja": "JR京都線", "train_type": "신쾌속", "train_type_ja": "新快速"}
    - 노선 이름이 사전에 통째로 있으면(예: 関空快速) 종별을 떼지 않는다.
    - 이름 끝의 종별(快速·新快速·特急 …)을 떼어 별도 필드로 준다. 이름에 종별이 없으면 NAVITIME의 종별 값(transport.type)을 쓰되,
      보통(各駅 정차)은 보여주지 않는다.
    - 한국어를 확보하지 못한 이름은 원어 그대로다.
    """
    text = _normalize(raw_name)
    base, type_ja = text, ""
    if korean_line_name(text) == text:  # 통째로는 사전에 없다 -> 끝의 종별을 뗀다
        match = _TRAIN_TYPE_PATTERN.search(text)
        if match and text[: match.start()]:
            base, type_ja = text[: match.start()], match.group(1)
    if not type_ja:
        declared = _normalize(transport_type)
        type_ja = declared if declared in TRAIN_TYPES and declared != DEFAULT_TRAIN_TYPE else ""
    if type_ja == DEFAULT_TRAIN_TYPE:
        type_ja = ""
    return {
        "line_name": korean_line_name(base),
        "line_name_ja": base,
        "train_type": TRAIN_TYPES.get(type_ja, ""),
        "train_type_ja": type_ja,
    }
